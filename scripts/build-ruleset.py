"""Generate the Spectral ruleset and fixtures from the measured SCIM profile."""
import re, yaml
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
STD = HERE / "standard" / "scim-2.0"
SPEC = STD / "spectral"; FIX = SPEC / "fixtures"; FIX.mkdir(parents=True, exist_ok=True)
p = yaml.safe_load((STD / "profile.yml").read_text())
m = p["method"]
core = [o for o in p["operations"] if o["tier"] == "core"]

def rid(o):
    return "scim-core-" + re.sub(r"[^a-z0-9]+", "-",
                                 f"{o['method']} {o['path']}".lower()).strip("-")

header = f"""# SPDX-License-Identifier: CC-BY-NC-SA-4.0
#
# SCIM 2.0, as a Spectral ruleset.
#
# GENERATED by scripts/build-ruleset.py from the measured profile.
#
# THIS RULESET DOES NOT CHECK CONFORMANCE TO RFC 7644, and the distinction matters. SCIM is
# ratified: the RFC is the conformance authority and says what a SCIM server must do. What
# it cannot tell you is what the industry actually built. These rules encode the MEASURED
# core — the operations declared by a majority of the {m['cohort']} providers publishing a
# SCIM path, out of {m['claimants']} that mention SCIM — so a document that passes is
# interoperable with the SCIM that exists, which is not the same as conformant.
#
# The severities say which is which: a missing measured-core operation is an error because
# real clients will break on it; a missing discovery endpoint is a WARNING, because the RFC
# does not compel it and a third of the cohort omits it.
#
# WHAT THIS DOES NOT CHECK
#   - RFC conformance. Filter syntax, PATCH semantics, sorting, pagination bounds,
#     attribute mutability and returned-ness are all normative and none is visible here.
#   - Runtime behaviour. Every SCIM operation is authenticated, so no probe is possible.
#   - Schema extensions. The enterprise User extension and vendor schemas are out of scope.
#
# Built-in functions only, so it runs unchanged in the browser validator.
formats: [oas3]

rules:
"""

rules = []
for o in core:
    esc = o["path"].replace("/", r"\\/").replace("{id}", r"\\{[^}]+\\}")
    rules.append(f"""
  {rid(o)}:
    description: >-
      `{o['method']} {o['path']}` is measured core: {o['providers_declaring']} of {m['cohort']}
      providers that publish a SCIM path declare it ({o['percent_of_cohort']}%). RFC 7644
      Section {o['rfc_section']}.
    message: "`{o['method']} {o['path']}` is not described. {o['percent_of_cohort']}% of the measured cohort declares it."
    severity: error
    documentationUrl: https://apicommons.org/standards/identity/#core
    given: "$"
    then:
      field: paths
      function: schema
      functionOptions:
        schema:
          type: object
          minProperties: 1
          not:
            propertyNames:
              not:
                pattern: "{esc}$"
""")

rules.append("""
  scim-discovery-endpoints:
    description: >-
      SCIM's three discovery endpoints — /ServiceProviderConfig, /ResourceTypes and /Schemas
      — are the only mechanism a client has for adapting to a server's capabilities. RFC 7644
      Section 4 does NOT compel a server to implement them: it says they "MAY be retrieved
      using HTTP GET", and uses SHALL only for the shape of the response if one comes. About
      a third of the measured cohort declares them. This is a warning rather than an error
      for exactly that reason — but a server without them leaves every client guessing.
    message: "No SCIM discovery endpoint described. Clients cannot learn what this server supports."
    severity: warn
    documentationUrl: https://apicommons.org/standards/identity/#discovery
    given: "$"
    then:
      field: paths
      function: schema
      functionOptions:
        schema:
          type: object
          minProperties: 1
          not:
            propertyNames:
              not:
                pattern: "(ServiceProviderConfig|ResourceTypes|Schemas)$"

  scim-media-type:
    description: >-
      RFC 7644 Section 3.1: "To identify this content, SCIM uses a media type of
      'application/scim+json'". A document that answers only application/json is describing
      something adjacent to SCIM, and a strict client checking the response type will reject
      it.
    message: "This response declares no `application/scim+json` content type."
    severity: warn
    documentationUrl: https://www.rfc-editor.org/rfc/rfc7644#section-3.1
    given: "$.paths[*][*].responses[?(@property == '200')].content"
    then:
      function: schema
      functionOptions:
        schema:
          type: object
          not:
            allOf:
              - required: ["application/json"]
              - maxProperties: 1

  scim-error-status-is-a-string:
    description: >-
      RFC 7644 Section 3.12 carries the HTTP status code INSIDE the error body as a JSON
      string — `"status": "404"`, not `"status": 404`. Describing it as an integer is a small
      error that produces a real one: a generated client deserialises the field, gets a type
      mismatch on every error response, and fails while handling a failure.
    message: "SCIM error `status` is a string carrying the HTTP status code, not an integer."
    severity: error
    documentationUrl: https://www.rfc-editor.org/rfc/rfc7644#section-3.12
    given: "$..properties.status[?(@property === 'type')]"
    then:
      function: pattern
      functionOptions:
        notMatch: "^(integer|number)$"
""")
(SPEC / "scim-profile.yaml").write_text(header + "".join(rules))


def spec(paths, scim_media=True, status_type="string"):
    ct = "application/scim+json" if scim_media else "application/json"
    out = {"openapi": "3.1.0", "info": {"title": "Fixture", "version": "1.0.0"}, "paths": {}}
    for path, methods in paths.items():
        out["paths"][path] = {mm.lower(): {
            "operationId": re.sub(r"[^a-zA-Z]", "", mm + path) or "op",
            "responses": {"200": {"description": "ok", "content": {ct: {"schema": {
                "type": "object",
                "properties": {"status": {"type": status_type}}}}}}}} for mm in methods}
    return out


by_path = {}
for o in core:
    by_path.setdefault(o["path"], []).append(o["method"])
disco = {"/ServiceProviderConfig": ["GET"], "/Schemas": ["GET"]}

(FIX / "clean.yaml").write_text(
    "# Every measured-core operation, the discovery endpoints, the SCIM media type, and\n"
    "# error status typed as the string the RFC specifies.\n"
    + yaml.dump(spec({**by_path, **disco}), sort_keys=False, width=100))
(FIX / "missing-core.yaml").write_text(
    "# An identity API that is not SCIM: no /Users, no discovery, no scim+json.\n"
    + yaml.dump(spec({"/people": ["GET", "POST"], "/people/{id}": ["GET"]},
                     scim_media=False), sort_keys=False, width=100))
(FIX / "noncompliant.yaml").write_text(
    "# The core operations are present, but served as plain JSON with the error status\n"
    "# typed as an integer — the two mistakes that break generated clients.\n"
    + yaml.dump(spec(by_path, scim_media=False, status_type="integer"),
                sort_keys=False, width=100))
print(f"ruleset     {len(core)} measured-core rules + 3 hygiene rules")
print(f"fixtures    clean.yaml, missing-core.yaml, noncompliant.yaml")
